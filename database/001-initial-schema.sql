/*
  TutorIA - instalacion inicial para PostgreSQL 18.x.
  Crear primero una base UTF-8 vacia y conectarse a ella con psql o pgAdmin.
  Ejecutar este archivo completo y despues 001-seed-data.sql.
*/
BEGIN;
SET LOCAL search_path TO public;
SET LOCAL TIME ZONE 'UTC';

DO $$
BEGIN
    IF current_setting('server_version_num')::integer NOT BETWEEN 180000 AND 189999 THEN
        RAISE EXCEPTION 'Se requiere PostgreSQL 18.x.';
    END IF;
    IF EXISTS (
        SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p')
    ) THEN
        RAISE EXCEPTION 'El esquema inicial requiere una base vacia. No ejecutarlo sobre datos existentes.';
    END IF;
END;
$$;

CREATE TABLE public.roles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL CONSTRAINT uq_roles_name UNIQUE,
    CONSTRAINT chk_role_name CHECK (name IN ('estudiante', 'coordinador', 'super_admin'))
);

CREATE TABLE public.planes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL CONSTRAINT uq_planes_nombre UNIQUE,
    max_cuentas integer,
    max_almacenamiento_gb numeric(5,2),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT ck_planes_limites CHECK (
        (max_cuentas IS NULL OR max_cuentas >= 0)
        AND (max_almacenamiento_gb IS NULL OR max_almacenamiento_gb >= 0))
);

CREATE TABLE public.instituciones (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre varchar(255) NOT NULL,
    dominio_permitido varchar(100),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE TABLE public.suscripciones (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institucion_id uuid NOT NULL CONSTRAINT uq_suscripciones_institucion UNIQUE
        REFERENCES public.instituciones(id) ON DELETE CASCADE,
    plan_id integer NOT NULL REFERENCES public.planes(id),
    limite_tokens_mensual bigint NOT NULL,
    fecha_inicio timestamp NOT NULL,
    fecha_fin timestamp NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT ck_suscripciones_limites CHECK (limite_tokens_mensual >= 0 AND fecha_fin > fecha_inicio)
);

CREATE TABLE public.users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institucion_id uuid REFERENCES public.instituciones(id) ON DELETE CASCADE,
    email varchar(255) NOT NULL CONSTRAINT uq_users_email UNIQUE,
    email_verified boolean NOT NULL DEFAULT false,
    password_hash varchar(255) NOT NULL,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,
    phone varchar(20),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE TABLE public.user_roles (
    user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    role_id integer NOT NULL REFERENCES public.roles(id) ON DELETE CASCADE,
    assigned_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE public.cursos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institucion_id uuid NOT NULL REFERENCES public.instituciones(id) ON DELETE CASCADE,
    nombre varchar(255) NOT NULL,
    codigo varchar(50),
    descripcion varchar(1000),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE public.estudiante_cursos (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid REFERENCES public.users(id),
    curso_id integer REFERENCES public.cursos(id),
    is_active boolean NOT NULL DEFAULT true,
    fecha_inscripcion timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT uq_estudiante_curso UNIQUE (user_id, curso_id)
);

CREATE TABLE public.configuracion_ia (
    curso_id integer PRIMARY KEY REFERENCES public.cursos(id) ON DELETE CASCADE,
    system_prompt varchar(2000) NOT NULL,
    temperatura numeric(3,2) NOT NULL DEFAULT 0.2,
    modos_permitidos varchar(200) NOT NULL DEFAULT 'chat,practicar,recursos',
    extender_conocimiento boolean NOT NULL DEFAULT false,
    updated_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT ck_configuracion_ia_temperatura CHECK (temperatura BETWEEN 0 AND 2)
);

CREATE TABLE public.sesiones_chat (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES public.users(id),
    curso_id integer NOT NULL REFERENCES public.cursos(id) ON DELETE CASCADE,
    titulo varchar(200) DEFAULT 'Nueva Conversación',
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE TABLE public.mensajes_chat (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    sesion_chat_id uuid NOT NULL REFERENCES public.sesiones_chat(id) ON DELETE CASCADE,
    rol varchar(20) NOT NULL,
    contenido text NOT NULL,
    citas_contexto_json text,
    imagen_nombre varchar(255),
    tipo_interaccion varchar(50) NOT NULL DEFAULT 'consulta',
    created_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT chk_rol_chat CHECK (rol IN ('assistant', 'user'))
);

CREATE TABLE public.actividades_agenda (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    curso_id integer NOT NULL REFERENCES public.cursos(id) ON DELETE CASCADE,
    titulo varchar(255) NOT NULL,
    descripcion text,
    tipo varchar(50) NOT NULL,
    fecha_limite timestamp NOT NULL,
    estado varchar(50) DEFAULT 'vigente',
    created_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE TABLE public.log_notificaciones (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES public.users(id),
    actividad_agenda_id uuid NOT NULL REFERENCES public.actividades_agenda(id) ON DELETE CASCADE,
    tipo_notificacion varchar(50) NOT NULL,
    estado_envio varchar(50) NOT NULL,
    fecha_ejecucion timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);

CREATE TABLE public.precios_modelo_ia (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor varchar(50) NOT NULL,
    modelo varchar(100) NOT NULL,
    precio_prompt_por_millon_usd numeric(12,6) NOT NULL,
    precio_completion_por_millon_usd numeric(12,6) NOT NULL,
    vigente_desde timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    vigente_hasta timestamp,
    is_active boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_precios_modelo_ia_version UNIQUE (proveedor, modelo, vigente_desde),
    CONSTRAINT ck_precios_modelo_ia_valores CHECK (
        precio_prompt_por_millon_usd >= 0 AND precio_completion_por_millon_usd >= 0
        AND (vigente_hasta IS NULL OR vigente_hasta > vigente_desde))
);

CREATE TABLE public.consumo_tokens (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institucion_id uuid NOT NULL REFERENCES public.instituciones(id),
    curso_id integer REFERENCES public.cursos(id) ON DELETE SET NULL,
    user_id uuid NOT NULL REFERENCES public.users(id),
    tipo_operacion varchar(50) NOT NULL,
    prompt_tokens integer NOT NULL,
    completion_tokens integer NOT NULL,
    costo_estimado_usd numeric(10,6) NOT NULL,
    precio_modelo_ia_id integer REFERENCES public.precios_modelo_ia(id) ON DELETE SET NULL,
    proveedor_modelo varchar(50),
    modelo_ia varchar(100),
    precio_prompt_por_millon_usd numeric(12,6),
    precio_completion_por_millon_usd numeric(12,6),
    fecha timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CONSTRAINT ck_consumo_tokens_valores CHECK (
        prompt_tokens >= 0 AND completion_tokens >= 0 AND costo_estimado_usd >= 0)
);

CREATE TABLE public.rag_ingestion_jobs (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    institucion_id uuid NOT NULL REFERENCES public.instituciones(id) ON DELETE CASCADE,
    curso_id integer NOT NULL REFERENCES public.cursos(id),
    coordinador_id uuid,
    estado varchar(20) NOT NULL DEFAULT 'queued',
    intento integer NOT NULL DEFAULT 1,
    documentos_json text NOT NULL DEFAULT '[]',
    chunks_indexados integer NOT NULL DEFAULT 0,
    archivos_procesados integer NOT NULL DEFAULT 0,
    respuesta_procesador_json text,
    error_message varchar(1000),
    created_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at timestamp NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    completed_at timestamp,
    CONSTRAINT ck_rag_ingestion_jobs_estado CHECK (
        estado IN ('queued', 'processing', 'completed', 'failed', 'unknown')),
    CONSTRAINT ck_rag_ingestion_jobs_metricas CHECK (
        intento >= 1 AND chunks_indexados >= 0 AND archivos_procesados >= 0)
);

CREATE INDEX idx_users_institucion ON public.users(institucion_id) WHERE is_active;
CREATE INDEX ix_cursos_institucion ON public.cursos(institucion_id);
CREATE UNIQUE INDEX uq_cursos_institucion_codigo ON public.cursos(institucion_id, codigo) WHERE codigo IS NOT NULL;
CREATE INDEX ix_estudiante_cursos_curso ON public.estudiante_cursos(curso_id, is_active);
CREATE INDEX ix_sesiones_chat_user_curso ON public.sesiones_chat(user_id, curso_id, updated_at DESC);
CREATE INDEX idx_mensajes_chat_sesion ON public.mensajes_chat(sesion_chat_id, created_at);
CREATE INDEX ix_actividades_agenda_curso ON public.actividades_agenda(curso_id, fecha_limite);
CREATE INDEX idx_actividades_fecha ON public.actividades_agenda(fecha_limite);
CREATE INDEX ix_log_notificaciones_actividad ON public.log_notificaciones(actividad_agenda_id);
CREATE INDEX ix_log_notificaciones_user ON public.log_notificaciones(user_id);
CREATE INDEX ix_consumo_tokens_institucion_fecha ON public.consumo_tokens(institucion_id, fecha)
    INCLUDE (user_id, curso_id, prompt_tokens, completion_tokens);
CREATE INDEX ix_consumo_tokens_user ON public.consumo_tokens(user_id);
CREATE UNIQUE INDEX uq_precio_modelo_ia_actual ON public.precios_modelo_ia(proveedor, modelo)
    WHERE is_active AND vigente_hasta IS NULL;
CREATE INDEX ix_rag_ingestion_jobs_curso_created ON public.rag_ingestion_jobs(curso_id, created_at DESC);
CREATE INDEX ix_rag_ingestion_jobs_institucion_estado ON public.rag_ingestion_jobs(institucion_id, estado);

COMMIT;
